// The key that encrypts the secrets saved here (backend/encryption.py): where it comes from, which secrets it
// decrypts, and what admins must do about it. The key itself is never sent to the browser.
import { useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { Alert, Button, Callout, Classes, Collapse, Icon, Intent, Tag } from "@blueprintjs/core";
import styled from "styled-components";

import { errorMessage } from "../../api/http";
import { toaster } from "../../toaster";
import { CopyCode } from "./values";
import { formatDate } from "../../settings/format";
import { rotateEncryptionKey } from "../api";


const Panel = styled.div`
  border: 1px solid var(--qa-border);
  border-radius: 6px;
  background: var(--qa-surface);
  padding: 14px 16px;
  margin-bottom: 16px;
  .facts {
    display: grid;
    grid-template-columns: max-content minmax(0, 1fr);
    gap: 6px 16px;
    margin: 10px 0 0;
    dt { color: var(--qa-text-muted); }
    dd { margin: 0; min-width: 0; overflow-wrap: anywhere; }
  }
  .bp6-callout { margin-top: 12px; }
  @media (max-width: 520px) {
    .facts { grid-template-columns: minmax(0, 1fr); dd { margin-bottom: 6px; } }
  }
`;

const source_labels = {
  env: name => <>From <code>${name}</code></>,
  file: path => <>From the file <code>{path}</code> (<code>$QABOARD_ENCRYPTION_KEY_FILE</code>)</>,
  generated: path => <>Generated by the server, in <code>{path}</code></>,
};

const Command = ({ command }) => <CopyCode text={command} what="the command"/>;

const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;


export const EncryptionPanel = ({ status }) => {
  const queryClient = useQueryClient();
  const [confirming, setConfirming] = useState(false);
  const [rotating, setRotating] = useState(false);
  const [explained, setExplained] = useState(false);
  if (!status) return null;
  const { key, secrets, previous_keys = [], problems = [] } = status;
  const total = secrets?.total ?? 0;
  const unreadable = secrets?.unreadable ?? [];
  const to_rotate = secrets?.to_rotate ?? 0;
  const in_current = key ? (secrets?.by_key?.[key.id] ?? 0) : 0;
  const ok = !problems.length && !unreadable.length;
  const unreadable_keys = [...new Set(unreadable.map(u => u.key_id).filter(Boolean))];

  const rotate = () => {
    setRotating(true);
    rotateEncryptionKey(queryClient)
      .then(result => toaster.show({ message: `Re-encrypted ${plural(result.rotated.length, 'secret')} with key ${result.key_id}${result.unreadable.length ? `, ${result.unreadable.length} can't be decrypted` : ''}`, intent: Intent.SUCCESS, icon: 'tick' }))
      .catch(error => toaster.show({ message: errorMessage(error), intent: Intent.DANGER, timeout: 10000 }))
      .finally(() => { setRotating(false); setConfirming(false); });
  };

  return <Panel aria-label="Encryption of the stored secrets" data-testid="encryption-panel">
    <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
      <Icon icon={ok ? 'lock' : 'unlock'} intent={ok ? Intent.SUCCESS : Intent.DANGER}/>
      <strong>Encryption of the stored secrets</strong>
      {key
        ? <Tag minimal round intent={ok ? Intent.SUCCESS : Intent.DANGER}>{ok ? 'OK' : 'Needs attention'}</Tag>
        : <Tag minimal round>No key yet</Tag>}
      <Button size="small" variant="minimal" icon={explained ? 'chevron-up' : 'help'} text="How it works" onClick={() => setExplained(!explained)} style={{ marginLeft: 'auto' }}/>
    </div>
    <dl className="facts">
      <dt>Key</dt>
      <dd>{key
        ? <><Tag minimal title="The key's fingerprint: it identifies the key without revealing it">{key.id}</Tag> {source_labels[key.source]?.(key.origin) ?? key.origin}
          {key.created_at && key.source === 'generated' && <span className={Classes.TEXT_MUTED}>, on {formatDate(key.created_at)}</span>}</>
        : <span className={Classes.TEXT_MUTED}>The server generates one when a secret is first saved, unless <code>$QABOARD_ENCRYPTION_KEY</code> is set.</span>}
      </dd>
      {previous_keys.length > 0 && <><dt>Also decrypts with</dt><dd>
        {previous_keys.map(previous => <div key={previous.id}><Tag minimal>{previous.id}</Tag> {source_labels[previous.source]?.(previous.origin) ?? <>From <code>${previous.origin}</code></>}</div>)}
      </dd></>}
      <dt>Stored secrets</dt>
      <dd>{total
        ? <>{plural(in_current, 'secret')} encrypted with this key{to_rotate > 0 && <>, {plural(to_rotate, 'older one')}</>}{unreadable.length > 0 && <>, <strong>{unreadable.length} unreadable</strong></>}</>
        : <span className={Classes.TEXT_MUTED}>None yet</span>}
        <span className={Classes.TEXT_MUTED}> (settings, sign-in providers' client secrets, users' refresh tokens)</span>
      </dd>
    </dl>

    {problems.map(problem => <Callout key={problem} intent={Intent.DANGER} icon="error" title="The key can't be read">{problem}</Callout>)}

    {unreadable.length > 0 && <Callout intent={Intent.DANGER} icon="error" title={`${plural(unreadable.length, 'secret')} can't be decrypted`}>
      They were encrypted with another key than this server's{unreadable_keys.length ? <> ({unreadable_keys.join(', ')})</> : null}.
      Restore that key (or set it in <code>$QABOARD_ENCRYPTION_KEY_PREVIOUS</code>), or enter these secrets again. Meanwhile QA-Board uses their defaults.
      <ul style={{ margin: '6px 0 0', paddingLeft: 18 }}>
        {unreadable.slice(0, 8).map((u, i) => <li key={i}>{u.label}</li>)}
        {unreadable.length > 8 && <li>and {unreadable.length - 8} more</li>}
      </ul>
    </Callout>}

    {key?.source === 'generated' && total > 0 && <Callout intent={Intent.WARNING} icon="floppy-disk" title="Back up this key">
      Database backups don't include it: without it, a restored database has no readable secrets. Copy it to your
      secret store as <code>QABOARD_ENCRYPTION_KEY</code>, from the server's shell: <Command command="qaboard-admin encryption show-key"/>.
      With several replicas, set it on all of them.
    </Callout>}

    {status.weak && <Callout intent={Intent.WARNING} icon="warning-sign" title="The key is short">
      Use at least 32 random characters, e.g. <Command command="openssl rand -base64 32"/>. Put the current key in <code>$QABOARD_ENCRYPTION_KEY_PREVIOUS</code>, the new one in <code>$QABOARD_ENCRYPTION_KEY</code>, then re-encrypt.
    </Callout>}

    {to_rotate > 0 && <Callout intent={Intent.PRIMARY} icon="refresh" title={`${plural(to_rotate, 'secret')} ${to_rotate === 1 ? 'uses' : 'use'} an older key, or ${to_rotate === 1 ? 'was' : 'were'} saved before encryption`}>
      <div style={{ marginBottom: 8 }}>Re-encrypt them with the current key. Then you can remove <code>$QABOARD_ENCRYPTION_KEY_PREVIOUS</code>.</div>
      <Button intent={Intent.PRIMARY} icon="refresh" text={`Re-encrypt ${plural(to_rotate, 'secret')}`} onClick={() => setConfirming(true)}/>
    </Callout>}

    <Collapse isOpen={explained}>
      <div className={Classes.TEXT_MUTED} style={{ marginTop: 12, fontSize: 13, maxWidth: 760 }}>
        <p>Secrets saved here (tokens, passwords) are encrypted in the database, and never sent back to the browser. The key is never stored in the database: a dump or a backup of it would otherwise hold both the secrets and what decrypts them. The server takes, in this order:</p>
        <ol style={{ paddingLeft: 18, margin: '0 0 8px' }}>
          <li><code>$QABOARD_ENCRYPTION_KEY</code>: any long random text. Recommended with several replicas.</li>
          <li><code>$QABOARD_ENCRYPTION_KEY_FILE</code>: a file holding it, e.g. a Docker or Kubernetes secret.</li>
          <li>A key it generates once in its data folder, readable only by the server. All the replicas must share that folder.</li>
        </ol>
        <p style={{ margin: 0 }}>To change the key: the old one in <code>$QABOARD_ENCRYPTION_KEY_PREVIOUS</code>, the new one in <code>$QABOARD_ENCRYPTION_KEY</code>, then re-encrypt here or with <Command command="qaboard-admin encryption rotate"/>. A replica whose key can't decrypt the stored secrets refuses to save new ones.</p>
      </div>
    </Collapse>

    <Alert
      isOpen={confirming}
      icon="refresh"
      intent={Intent.PRIMARY}
      confirmButtonText="Re-encrypt"
      cancelButtonText="Cancel"
      loading={rotating}
      onConfirm={rotate}
      onCancel={() => setConfirming(false)}
    >
      Re-encrypt {plural(to_rotate, 'secret')} with key <strong>{key?.id}</strong>? Servers that only have the older key can't read them afterwards.
    </Alert>
  </Panel>;
};
