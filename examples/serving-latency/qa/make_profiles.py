#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.9"
# dependencies = []
# ///
"""
Writes the load profiles, the inputs of the serving-latency example: inputs/profiles/<profile>-<level>.yaml and
inputs/profiles/ramp.yaml. Deterministic: the same files every time. They are committed; edit this script, not them.

  uv run qa/make_profiles.py

A profile gives the arrival process, the request rate, the payload sizes and the key distribution. gateway-bench
generates the schedule from it and the run's seed (qa/main.py).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'inputs' / 'profiles'

# requests/s: fixed numbers, so a commit that changes the gateway's capacity shows up as a change
LEVELS = {'low': 2000, 'mid': 4000, 'high': 6000}
KEYS = {'distribution': 'zipf', 's': 0.9, 'n': 100_000}
DEADLINE_MS = 12

PROFILES = {
    'steady': {
        'about': 'Poisson arrivals, 8 tokens per request',
        'arrivals': {'process': 'poisson'},
        'tokens': {'distribution': 'fixed', 'n': 8},
    },
    'bursty': {
        'about': 'on/off arrivals: 5x the base rate for 200 ms, every 2 s or so, 8 tokens per request',
        'arrivals': {'process': 'bursty', 'factor': 5, 'burst_ms': 200, 'every_ms': 2000},
        'tokens': {'distribution': 'fixed', 'n': 8},
    },
    'heavy-tail': {
        'about': 'Poisson arrivals, request sizes from a Pareto distribution (alpha 1.3), 1 to 256 tokens',
        'arrivals': {'process': 'poisson'},
        'tokens': {'distribution': 'pareto', 'alpha': 1.3, 'min': 1, 'max': 256},
    },
}
RAMP = {
    'about': 'Poisson arrivals, the rate going from 20% to 120% of the high level in 10 steps of 0.5 s, 8 tokens per request',
    'arrivals': {'process': 'ramp', 'from': 0.2, 'to': 1.2, 'steps': 10, 'step_ms': 500},
    'tokens': {'distribution': 'fixed', 'n': 8},
}


def flow(d: dict) -> str:
    return '{' + ', '.join(f'{k}: {v}' for k, v in d.items()) + '}'


def write(name: str, profile: str, level: str, rate: int, spec: dict):
    text = '\n'.join([
        f"# {name}: {spec['about']} (high: {rate:,} requests/s)." if profile == 'ramp' else
        f"# {name}: {spec['about']}, {rate:,} requests/s on average.",
        '# Generated by qa/make_profiles.py: edit it, not this file.',
        f'profile: {profile}',
        f'level: {level}',
        f'rate: {rate}',
        f"arrivals: {flow(spec['arrivals'])}",
        f"tokens: {flow(spec['tokens'])}",
        f'keys: {flow(KEYS)}',
        f'deadline_ms: {DEADLINE_MS}',
        '',
    ])
    (OUT / f'{name}.yaml').write_text(text)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for profile, spec in PROFILES.items():
        for level, rate in LEVELS.items():
            write(f'{profile}-{level}', profile, level, rate, spec)
    write('ramp', 'ramp', 'high', LEVELS['high'], RAMP)
    print(f'{len(PROFILES) * len(LEVELS) + 1} profiles in {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
